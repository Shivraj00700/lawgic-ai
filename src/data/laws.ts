/**
 * Builds a link to the official India Code portal, the Government of India's
 * legislation repository.
 *
 * India Code's per-act "handle" URLs are opaque and change between releases, so
 * a guessed handle risks shipping a dead link — which would be the worst
 * possible failure for a product whose whole claim is a verifiable citation.
 * The `simple-search` path is stable and deterministic, and lands the user on
 * the official text of the named Act.
 */
function indiaCode(actName: string): string {
  return `https://www.indiacode.nic.in/simple-search?query=${encodeURIComponent(actName).replace(/%20/g, "+")}`;
}

